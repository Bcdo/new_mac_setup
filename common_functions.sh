#!/bin/bash

# Common output functions for consistent terminal styling
# Usage: source ./common_functions.sh

# Color definitions
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[0;33m'
BLUE='\033[0;34m'
MAGENTA='\033[0;35m'
CYAN='\033[0;36m'
WHITE='\033[0;37m'
BOLD='\033[1m'
NC='\033[0m' # No Color

# Status functions
log_header() {
    echo ""
    echo -e "${BOLD}${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
    echo -e "${BOLD}${BLUE}  🚀 $1${NC}"
    echo -e "${BOLD}${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
    echo ""
}

log_step() {
    echo ""
    echo -e "${BOLD}${CYAN}🔧 $1${NC}"
    echo ""
}

log_success() {
    echo -e "${GREEN}✅ $1${NC}"
}

log_warning() {
    echo -e "${YELLOW}⚠️  $1${NC}"
}

log_error() {
    echo -e "${RED}❌ $1${NC}"
}

log_info() {
    echo -e "${BLUE}ℹ️  $1${NC}"
}

log_progress() {
    echo -e "${MAGENTA}⏳ $1${NC}"
}

log_complete() {
    echo ""
    echo -e "${BOLD}${GREEN}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
    echo -e "${BOLD}${GREEN}  🎉 $1${NC}"
    echo -e "${BOLD}${GREEN}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
    echo ""
}

# Function to show what would be changed (for dry runs)
log_would_set() {
    echo -e "${CYAN}  📝 Would set: ${YELLOW}$1${NC}"
    if [ -n "$2" ]; then
        echo -e "${BLUE}  📖 Current value: ${WHITE}$2${NC}"
    fi
}

log_would_run() {
    echo -e "${MAGENTA}  🚀 Would run: ${WHITE}$1${NC}"
}

# Function to show actual changes being made
log_setting() {
    echo -e "${CYAN}  📝 Setting: ${YELLOW}$1${NC}"
}

log_running() {
    echo -e "${MAGENTA}  🚀 Running: ${WHITE}$1${NC}"
}
